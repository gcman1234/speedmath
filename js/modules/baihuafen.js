'use strict';

/* ============================================================
 * 模块：百化分背诵（键盘输入型）
 * 给出百分数，填对应分数 1/x 的分母。
 * 题库严格固定（43 条），每局随机抽 10 题且不重复。
 * ============================================================ */

/* [百分数字符串, 分母数值] —— 请勿随意增删，保持与背诵表一致 */
const BAIHUAFEN_BANK = [
  ['6.25%', 16], ['6.7%', 15], ['7%', 14.3], ['7.3%', 13.7], ['7.7%', 13],
  ['8%', 12.5], ['8.3%', 12], ['9%', 11], ['10%', 10], ['11%', 9],
  ['12%', 8.3], ['12.5%', 8], ['13%', 7.7], ['13.7%', 7.3], ['14.3%', 7],
  ['15%', 6.7], ['16%', 6.25], ['16.7%', 6], ['18%', 5.6], ['19%', 5.3],
  ['20%', 5], ['22%', 4.5], ['24%', 4.2], ['25%', 4], ['27%', 3.7],
  ['30%', 3.3], ['33%', 3], ['37%', 2.7], ['40%', 2.5], ['42%', 2.4],
  ['45%', 2.2], ['50%', 2], ['53%', 1.9], ['56%', 1.8], ['60%', 1.67],
  ['62.5%', 1.6], ['67%', 1.5], ['70%', 1.43], ['73%', 1.37], ['77%', 1.3],
  ['80%', 1.25], ['83%', 1.2], ['90%', 1.1]
];

/* 洗牌抽屉：抽完自动重洗，保证每局 10 题互不重复 */
let baihuafenDeck = [];

function baihuafenDraw() {
  if (baihuafenDeck.length === 0) {
    baihuafenDeck = shuffle(BAIHUAFEN_BANK.slice());
  }
  return baihuafenDeck.pop();
}

registerModule({
  id: 'baihuafen',
  name: '百化分背诵',
  icon: '📖',
  desc: '百分数化分数，43 组对照',
  total: 10,                       // 每局题数

  /* 查表附表：由题库生成，保证与考题绝对一致。
   * 声明后答题页右侧圆钮变为"查表"，点击弹出对照表（查表期间计时暂停）。 */
  cheatSheet: {
    title: '百化分对照表',
    rows: BAIHUAFEN_BANK.map(e => [e[0], `1/${e[1]}`])
  },

  makeQuestion() {
    const item = baihuafenDraw();
    const pct = item[0];
    const den = item[1];
    return {
      type: 'keypad',
      prompt: `${pct} = 1/( )`,    // 结算页纯文本
      correctText: `1/${den}`,     // 结算页"正确答案"列显示
      answer: den,                 // 判题用数值（小数精确比较）
      // 答题区：分数竖式，数字实时填入分母的 ( ? ) 中
      promptHTML:
        `${pct} = ` +
        `<span class="frac">` +
        `<span class="frac-n">1</span>` +
        `<span class="frac-line"></span>` +
        `<span class="frac-d">(<span class="q-slot">?</span>)</span>` +
        `</span>`
    };
  }
});
